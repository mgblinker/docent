#!/usr/bin/env node
// Flags Angular code that reinvents an NSwag-generated API client instead of
// using it: a file that talks to the backend via raw HttpClient and also
// locally defines an interface/type whose name already exists in one of the
// generated client files is a strong, cheap-to-check signal of duplicated
// request/response shapes (found via the booking-form flow: it hand-rolls
// CreateBookingRequest/BookingConfirmation instead of using CalendarClient,
// which already generates a CreateBookingRequest type for the same call).
//
// Generated clients live in several different directories across the
// Angular app (main app, immobroker/, planning/, ...), not just one - a file
// is treated as "generated" if it carries NSwag's own `<auto-generated>`
// header, not by hardcoding a directory path. This also matters in the
// other direction: two independently generated clients can legitimately
// share a common DTO name (ProblemDetails, FileResponse - standard NSwag
// boilerplate for error/file responses); names that appear in more than a
// couple of generated files are excluded from the check as too generic to
// mean anything.
//
// This does NOT try to resolve exact URL-to-endpoint matches (raw HttpClient
// calls often build URLs dynamically) - the type-name collision is the
// reliable part; treat it as "worth a look", not proof of a bug.
//
// Output: JSON array to stdout (or --out <file>), plus a generated doc page.

import fs from "fs";
import path from "path";

const ANGULAR_ROOT = "/Users/michael/Projects/Processity.WebApp.Angular/src";
const DOC_OUT = "/Users/michael/Projects/Processity.Docs/docs/flows/frontend-api-inconsistencies.md";
const MAX_FILES_PER_TYPE_NAME = 2; // names appearing in more are treated as generic NSwag boilerplate

function walkTsFiles(dir, out) {
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const entry of entries) {
    if (entry.name === "node_modules" || entry.name.startsWith(".")) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walkTsFiles(full, out);
    else if (entry.name.endsWith(".ts") && !entry.name.endsWith(".spec.ts")) out.push(full);
  }
}

function isNSwagGenerated(content) {
  return content.includes("<auto-generated>") && content.includes("NSwag");
}

function exportedTypeNames(content) {
  const names = [];
  const re = /export (?:interface|class) (\w+)/g;
  let m;
  while ((m = re.exec(content))) names.push(m[1]);
  return names;
}

function usesRawHttpClient(content) {
  return /inject\(HttpClient\)|:\s*HttpClient\b/.test(content);
}

function localTypeNames(content) {
  const names = [];
  const re = /^export interface (\w+)/gm;
  let m;
  while ((m = re.exec(content))) names.push(m[1]);
  return names;
}

function main() {
  const allFiles = [];
  walkTsFiles(ANGULAR_ROOT, allFiles);

  const generatedFiles = [];
  const candidateFiles = [];
  for (const file of allFiles) {
    const content = fs.readFileSync(file, "utf-8");
    if (isNSwagGenerated(content)) {
      generatedFiles.push({ file, content });
    } else {
      candidateFiles.push({ file, content });
    }
  }
  console.error(`Found ${generatedFiles.length} NSwag-generated files (by <auto-generated> header) across the app.`);

  // typeName -> list of generated files that export it
  const typeToClientFiles = new Map();
  for (const { file, content } of generatedFiles) {
    for (const name of exportedTypeNames(content)) {
      if (!typeToClientFiles.has(name)) typeToClientFiles.set(name, []);
      typeToClientFiles.get(name).push(path.relative(ANGULAR_ROOT, file));
    }
  }
  const meaningfulTypeToClientFile = new Map();
  for (const [name, files] of typeToClientFiles) {
    if (files.length <= MAX_FILES_PER_TYPE_NAME) meaningfulTypeToClientFile.set(name, files[0]);
  }
  console.error(
    `${meaningfulTypeToClientFile.size} of ${typeToClientFiles.size} exported type names are specific enough to check (appear in <=${MAX_FILES_PER_TYPE_NAME} generated files).`,
  );

  const findings = [];
  for (const { file, content } of candidateFiles) {
    if (!usesRawHttpClient(content)) continue;

    for (const name of localTypeNames(content)) {
      const clientFile = meaningfulTypeToClientFile.get(name);
      if (!clientFile) continue;
      findings.push({
        file: path.relative(ANGULAR_ROOT, file),
        duplicatedType: name,
        alreadyGeneratedIn: clientFile,
      });
    }
  }

  const output = JSON.stringify(findings, null, 2);
  const outIdx = process.argv.indexOf("--out");
  if (outIdx !== -1 && process.argv[outIdx + 1]) {
    fs.writeFileSync(process.argv[outIdx + 1], output);
  } else {
    process.stdout.write(output);
  }
  console.error(`Found ${findings.length} type-name collisions between raw-HttpClient files and generated clients.`);

  const byFile = new Map();
  for (const f of findings) {
    if (!byFile.has(f.file)) byFile.set(f.file, []);
    byFile.get(f.file).push(f);
  }

  const sections = [...byFile.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([file, items]) => {
      const rows = items
        .map((i) => `- \`${i.duplicatedType}\` — already generated in \`${i.alreadyGeneratedIn}\``)
        .join("\n");
      return `## ${file}\n\n${rows}`;
    })
    .join("\n\n");

  const docContent = `---
type: flows
---

# Frontend API Client Inconsistencies

**Auto-generated from code — do not hand-edit.** Regenerate with
\`tools/detect-frontend-api-inconsistencies.mjs\` in the docs repo.

Flags Angular files that call the backend via raw \`HttpClient\` while also
locally defining an interface whose name already exists in an NSwag-generated
API client somewhere in the app (identified by NSwag's own
\`<auto-generated>\` header, not a fixed directory — the app has several
generated-client directories: the main one plus per-product ones under
\`immobroker/\` and \`planning/\`). Names that appear in more than
${MAX_FILES_PER_TYPE_NAME} generated clients (e.g. \`ProblemDetails\`,
\`FileResponse\`) are treated as generic NSwag boilerplate and excluded —
matching against those doesn't indicate real duplication. That still leaves
a name collision as a signal, not proof, that the file is reinventing a
request/response shape the generated client already provides.

Known root cause for at least one case: **anonymous/public-facing pages**
(e.g. the guest booking flow) can't use the authenticated NSwag client as-is
(it likely assumes an auth interceptor that doesn't apply to unauthenticated
routes), so they reimplement the call with hand-rolled types instead. Worth
checking whether each flagged file below is that same legitimate case or an
avoidable duplication.

${findings.length === 0 ? "No collisions found." : sections}
`;
  fs.mkdirSync(path.dirname(DOC_OUT), { recursive: true });
  fs.writeFileSync(DOC_OUT, docContent);
  console.error(`Wrote doc page to ${DOC_OUT}`);
}

main();
